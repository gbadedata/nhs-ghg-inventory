"""Write the CSV outputs and the markdown summary and trust profile."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from . import config
from .quality import CHECKS

NHS_HEADLINE_KWH = 11.2e9  # "11.2 billion kWh total energy consumption", ERIC 2025/26 summary page


def _table(df: pd.DataFrame, fmt: dict[str, str] | None = None) -> str:
    fmt = fmt or {}
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(format(v, fmt[c]) if c in fmt and pd.notna(v) else ("" if pd.isna(v) else str(v)))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _title(name: str) -> str:
    small = {"AND", "OF", "UPON", "THE", "FOR"}
    words = [w.lower() if w in small else w.capitalize() for w in name.split()]
    words = ["NHS" if w.lower() == "nhs" else w for w in words]
    if words:
        words[0] = words[0][0].upper() + words[0][1:]
    return " ".join(words)


def write_outputs(summary: pd.DataFrame, items: pd.DataFrame, flags: pd.DataFrame,
                  activity: pd.DataFrame, source_label: str, out: Path = config.OUTPUT_DIR) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / "trusts").mkdir(exist_ok=True)
    num = summary.select_dtypes("number").columns
    summary.assign(**{c: summary[c].round(3) for c in num}).to_csv(out / "trust_inventory_2025_26.csv", index=False)
    nz = items[items["activity_value"] != 0].copy()
    nz["kgco2e"] = nz["kgco2e"].round(3)
    nz.to_csv(out / "line_items_2025_26.csv", index=False)
    flags.to_csv(out / "data_quality_flags_2025_26.csv", index=False)
    (out / "SUMMARY.md").write_text(summary_md(summary, items, flags, activity, source_label), encoding="utf-8")
    (out / "trusts" / "RDE.md").write_text(trust_profile_md("RDE", summary, items, flags, activity), encoding="utf-8")


def summary_md(summary: pd.DataFrame, items: pd.DataFrame, flags: pd.DataFrame,
               activity: pd.DataFrame, source_label: str) -> str:
    tot = summary.select_dtypes("number").sum()
    kt = lambda x: x / 1000.0  # noqa: E731
    energy = tot["energy_kwh"]
    s = [
        "# NHS trust estate GHG inventory, 2025/26",
        "",
        f"Generated by `nhs-ghg run`. Activity data: NHS England ERIC 2025/26 site data "
        "(1 April 2025 to 31 March 2026). Factors: DESNZ 2025 conversion factors. Both under the Open Government "
        "Licence v3.0. Method and every assumption: [METHODOLOGY.md](../METHODOLOGY.md).",
        "",
        f"**Scope:** {len(summary)} NHS trusts, {int(tot['n_energy_sites']):,} of {int(tot['n_sites']):,} sites reporting "
        "energy. Estate energy, water and waste only: not the full NHS footprint (no medicines, anaesthetic gases, "
        "travel or supply chain).",
        "",
        "## Totals (kt CO2e)",
        "",
        _table(pd.DataFrame([
            {"Scope": "Scope 1", "Location-based": kt(tot["scope1_t"]), "Market-based": kt(tot["scope1_t"])},
            {"Scope": "Scope 2", "Location-based": kt(tot["scope2_location_t"]), "Market-based": kt(tot["scope2_market_t"])},
            {"Scope": "Scope 3 (categories 1, 3, 5)", "Location-based": kt(tot["scope3_t"]), "Market-based": kt(tot["scope3_t"])},
            {"Scope": "**Total**", "Location-based": kt(tot["total_location_t"]), "Market-based": kt(tot["total_market_t"])},
            {"Scope": "Outside of scopes (biogenic CO2)", "Location-based": kt(tot["outside_scopes_t"]), "Market-based": kt(tot["outside_scopes_t"])},
        ]), {"Location-based": ",.1f", "Market-based": ",.1f"}),
        "",
        "Market-based Scope 2 counts REGO-backed green-tariff electricity at zero and the rest at the grid "
        "average. It is approximate: DESNZ publishes no residual-mix factor (decision D5).",
        "",
        "## By line",
        "",
    ]
    by_line = (items.groupby(["scope", "category", "line", "factor_id"], sort=False)["kgco2e"].sum() / 1e6).reset_index()
    by_line = by_line.rename(columns={"kgco2e": "kt CO2e"})
    s += [_table(by_line, {"kt CO2e": ",.2f"}), ""]

    s += ["## By trust type", ""]
    bt = summary.groupby("trust_type").agg(
        trusts=("trust_code", "count"),
        energy_GWh=("energy_kwh", lambda x: x.sum() / 1e6),
        s1_s2_loc_kt=("scope1_t", "sum"),
        s2=("scope2_location_t", "sum"),
        gia=("gia_energy_reporting_m2", "sum"),
    )
    bt["s1_s2_loc_kt"] = (bt["s1_s2_loc_kt"] + bt.pop("s2")) / 1000.0
    bt["kg_per_m2"] = bt["s1_s2_loc_kt"] * 1e6 / bt.pop("gia")
    bt = bt.sort_values("s1_s2_loc_kt", ascending=False).reset_index()
    s += [_table(bt.rename(columns={"trust_type": "Trust type", "trusts": "Trusts", "energy_GWh": "Energy GWh",
                                    "s1_s2_loc_kt": "Scope 1+2 kt", "kg_per_m2": "kg CO2e/m²"}),
                 {"Energy GWh": ",.0f", "Scope 1+2 kt": ",.1f", "kg CO2e/m²": ",.1f"}), "",
          "Intensity uses the floor area of energy-reporting sites only.", ""]

    s += ["## Largest 10 trusts (location-based total)", ""]
    top = summary.nlargest(10, "total_location_t")[["trust_code", "trust_name", "total_location_t", "s1_s2_location_kg_per_m2"]].copy()
    top["trust_name"] = top["trust_name"].map(_title)
    top["total_location_t"] = top["total_location_t"] / 1000.0
    s += [_table(top.rename(columns={"trust_code": "Code", "trust_name": "Trust", "total_location_t": "kt CO2e",
                                     "s1_s2_location_kg_per_m2": "S1+2 kg/m²"}), {"kt CO2e": ",.1f", "S1+2 kg/m²": ",.1f"}), ""]

    chp = activity["chp_gas_input_kwh"].sum()
    s += [
        "## Reconciliation",
        "",
        f"- **Energy total:** {energy / 1e9:,.2f} billion kWh, against the {NHS_HEADLINE_KWH / 1e9:.1f} billion kWh "
        f"NHS England publishes for 2025/26. Adding the separately reported CHP gas input "
        f"({chp / 1e9:,.2f} billion kWh) would give {(energy + chp) / 1e9:,.2f} billion, so the published "
        "total confirms that 'Gas consumed' already includes CHP feed (D2).",
        f"- **Waste:** {tot['waste_quantified_t']:,.0f} t quantified; {tot['waste_unquantified_t']:,.0f} t of clinical, "
        "offensive and on-site-treated waste is reported but not converted, because DESNZ has no factor for "
        "those routes (D9). This is the largest known gap in Scope 3.",
        "",
        "## Data-quality flags",
        "",
        "Raised for a reviewer to query with the trust. No figure is changed by a flag.",
        "",
    ]
    counts = flags.groupby("check").size()
    s += [_table(pd.DataFrame([{"Check": k, "Trusts": int(counts.get(k, 0)), "What it means": v} for k, v in CHECKS.items()])),
          "", "Full list: [data_quality_flags_2025_26.csv](data_quality_flags_2025_26.csv).", ""]
    return "\n".join(s)


def trust_profile_md(code: str, summary: pd.DataFrame, items: pd.DataFrame,
                     flags: pd.DataFrame, activity: pd.DataFrame) -> str:
    r = summary.set_index("trust_code").loc[code]
    li = items[(items["trust_code"] == code) & (items["activity_value"] != 0)].copy()
    li["tCO2e"] = li["kgco2e"] / 1000.0
    show = li[["scope", "line", "activity", "activity_value", "activity_unit", "factor_id", "factor_kgco2e_per_unit", "basis", "tCO2e"]]
    a = activity.set_index("trust_code").loc[code]
    f = flags[flags["trust_code"] == code]
    unq = config.mapping()["unquantified_waste"]
    s = [
        f"# {_title(r['trust_name'])} ({code}) - 2025/26",
        "",
        "A worked example of the audit trail: every number below can be recomputed by hand as activity x factor, "
        "and every factor found in the DESNZ 2025 flat file by its ID.",
        "",
        f"- Trust type: {r['trust_type'].title()}; {_title(r['region'])}",
        f"- Sites: {int(r['n_sites'])}, of which {int(r['n_energy_sites'])} report energy "
        f"({r['gia_energy_reporting_m2']:,.0f} m² of floor area). The other {int(r['n_sites'] - r['n_energy_sites'])} "
        "report 'Not Applicable' for energy (leased sites the landlord services wholly or partly, or unoccupied). "
        "Some of that use may belong in the trust's own Scope 1-2; it is a known gap (D3).",
        "",
        "## Totals (t CO2e)",
        "",
        _table(pd.DataFrame([
            {"": "Scope 1", "t CO2e": r["scope1_t"]},
            {"": "Scope 2 (location)", "t CO2e": r["scope2_location_t"]},
            {"": "Scope 2 (market, approximate)", "t CO2e": r["scope2_market_t"]},
            {"": "Scope 3 (cat 1, 3, 5)", "t CO2e": r["scope3_t"]},
            {"": "Total (location)", "t CO2e": r["total_location_t"]},
            {"": "Total (market)", "t CO2e": r["total_market_t"]},
            {"": "Outside of scopes (biogenic CO2)", "t CO2e": r["outside_scopes_t"]},
        ]), {"t CO2e": ",.1f"}),
        "",
        f"Scope 1+2 (location) intensity: {r['s1_s2_location_kg_per_m2']:,.1f} kg CO2e/m². "
        f"Energy: {r['energy_kwh'] / 1e6:,.2f} GWh.",
        "",
        "## Line items",
        "",
        _table(show, {"activity_value": ",.2f", "factor_kgco2e_per_unit": ".5f", "tCO2e": ",.2f"}),
        "",
        "## Waste not converted",
        "",
        _table(pd.DataFrame([{"Stream": k, "Tonnes": a[k]} for k in unq if a[k]]), {"Tonnes": ",.2f"}),
        "",
        "## Data-quality flags",
        "",
        _table(f[["check", "description", "detail"]]) if len(f) else "None raised.",
        "",
    ]
    return "\n".join(s)
